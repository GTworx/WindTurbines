"""ReportingAgent (spec Section 2.5).

Automated artifact compilation:
  * Markdown wiki pages under ``Wiki/Turbines/{Turbine_ID}/`` (index + per-blade).
  * Annotated image copies under ``Runs/{Run_ID}/annotated/`` (spec 4.3).
  * A self-contained static HTML dashboard under ``Runs/{Run_ID}/dashboard/``
    with filterable cards and severity/blade/defect filtering (spec 2.5.2).
"""

from __future__ import annotations

import json
import os
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List, Optional

from ..models import TurbineReport
from ..overlay import annotate_blade
from ..events import EventBus, REPORT_GENERATED
from .base import BaseAgent


class ReportingAgent(BaseAgent):
    name = "ReportingAgent"

    def __init__(self, config, event_bus: Optional[EventBus] = None,
                 run_id: Optional[str] = None, **kwargs: Any):
        super().__init__(config, event_bus=event_bus, run_id=run_id, **kwargs)
        self.run_dir = config.runs_dir / (run_id or "adhoc")

    # ------------------------------------------------------------------
    def generate(self, turbine: TurbineReport) -> Dict[str, Any]:
        self.run_dir.mkdir(parents=True, exist_ok=True)
        annotated_dir = self.run_dir / "annotated"
        wiki_turbine_dir = self.config.wiki_dir / "Turbines" / turbine.turbine_id

        annotated_paths = self._annotate(turbine, annotated_dir)
        wiki_index = self._write_wiki(turbine, wiki_turbine_dir, annotated_dir)
        dashboard = self._write_dashboard(turbine, self.run_dir / "dashboard" / "index.html", annotated_dir)

        artifacts = {
            "wiki_index": str(wiki_index),
            "wiki_dir": str(wiki_turbine_dir),
            "dashboard": str(dashboard),
            "annotated_dir": str(annotated_dir),
            "n_annotated": len(annotated_paths),
        }
        self.log_info("REPORT_GENERATED", "Reporting artifacts generated", detail=artifacts)
        self.events.publish(REPORT_GENERATED, artifacts)
        return artifacts

    # -- annotated overlays ---------------------------------------------
    def _annotated_rel(self, blade_id: str, src: Path, annotated_dir: Path) -> Path:
        return annotated_dir / blade_id / (src.stem + ".annotated" + src.suffix)

    def _annotate(self, turbine: TurbineReport, annotated_dir: Path) -> List[str]:
        annotated_dir.mkdir(parents=True, exist_ok=True)
        produced: List[str] = []
        for br in turbine.blade_reports:
            for ir in br.image_results:
                if not ir.detections:
                    continue
                src = Path(ir.image_path)
                if not src.exists():
                    continue
                rel = annotate_blade(src, ir.detections, annotated_dir / br.blade_id)
                if rel:
                    produced.append(f"{br.blade_id}/{rel}")
        return produced

    # -- wiki -----------------------------------------------------------
    def _write_wiki(self, turbine: TurbineReport, turbine_dir: Path, annotated_dir: Path) -> Path:
        turbine_dir.mkdir(parents=True, exist_ok=True)
        now = datetime.now(timezone.utc).isoformat()

        index_lines: List[str] = [
            f"# Turbine {turbine.turbine_id}",
            "",
            f"_Generated by BladeRunner at {now}_",
            "",
            f"**Overall health index:** {turbine.overall_health_index}/100",
            "",
            "## Defect distribution",
            "",
            "| Defect class | Count |",
            "| --- | --- |",
        ]
        for cls, count in sorted(turbine.defect_distribution().items()):
            index_lines.append(f"| {cls} | {count} |")
        index_lines += ["", "## Blades", ""]
        for br in turbine.blade_reports:
            index_lines.append(f"- [{br.blade_id}]({br.blade_id.lower().replace('_', '-')}.md) — health {br.health_index}/100, {len(br.detections)} defects")

        index_path = turbine_dir / "index.md"
        index_path.write_text("\n".join(index_lines) + "\n", encoding="utf-8")

        for br in turbine.blade_reports:
            self._write_blade_wiki(br, turbine_dir)

        return index_path

    def _write_blade_wiki(self, br, turbine_dir: Path) -> Path:
        lines = [
            f"# {br.turbine_id} / {br.blade_id}",
            "",
            f"**Health index:** {br.health_index}/100",
            "",
            "## Defect distribution",
            "",
            "| Defect class | Count |",
            "| --- | --- |",
        ]
        for cls, count in sorted(br.defect_distribution().items()):
            lines.append(f"| {cls} | {count} |")
        lines += ["", "## Images with detections", ""]
        for ir in br.image_results:
            if not ir.detections:
                continue
            lines.append(f"### `{ir.image_name}`")
            md = ir.metadata
            if md:
                bits = []
                if md.distance_from_root_m is not None:
                    bits.append(f"span {md.distance_from_root_m} m")
                if md.surface_face:
                    bits.append(md.surface_face)
                if md.edge:
                    bits.append(md.edge)
                if md.timestamp:
                    bits.append(md.timestamp)
                if bits:
                    lines.append("_" + " · ".join(bits) + "_")
                    lines.append("")
            lines += ["| Class | Severity | BBox | Confidence |", "| --- | --- | --- | --- |"]
            for d in ir.detections:
                bbox = f"[{', '.join(str(x) for x in d.bbox)}]"
                lines.append(f"| {d.defect_class} | {d.severity} | {bbox} | {d.confidence:.2f} |")
            lines.append("")
        slug = br.blade_id.lower().replace("_", "-")
        out = turbine_dir / f"{slug}.md"
        out.write_text("\n".join(lines) + "\n", encoding="utf-8")
        return out

    # -- static HTML dashboard ------------------------------------------
    def _rel_to_dashboard(self, path: Path, dashboard_file: Path) -> str:
        try:
            return os.path.relpath(path, dashboard_file.parent).replace(os.sep, "/")
        except ValueError:
            return path.as_posix()

    def _write_dashboard(self, turbine: TurbineReport, dashboard_file: Path, annotated_dir: Path) -> Path:
        dashboard_file.parent.mkdir(parents=True, exist_ok=True)
        now = datetime.now(timezone.utc).isoformat()

        # Build a flat list of "cards" (one per image that has detections).
        cards = []
        for br in turbine.blade_reports:
            for ir in br.image_results:
                if not ir.detections:
                    continue
                src = Path(ir.image_path)
                ann_path = self._annotated_rel(br.blade_id, src, annotated_dir)
                ann_rel = self._rel_to_dashboard(ann_path, dashboard_file)
                ann_exists = ann_path.exists()
                cards.append({
                    "blade": br.blade_id,
                    "image": ir.image_name,
                    "src_rel": self._rel_to_dashboard(src, dashboard_file),
                    "ann_rel": ann_rel if ann_exists else None,
                    "span": ir.metadata.distance_from_root_m if ir.metadata else None,
                    "surface": ir.metadata.surface_face if ir.metadata else None,
                    "max_severity": max(d.severity for d in ir.detections),
                    "detections": [
                        {"class": d.defect_class, "severity": d.severity,
                         "bbox": d.bbox, "confidence": round(d.confidence, 3)}
                        for d in ir.detections
                    ],
                })

        classes = sorted({d["class"] for c in cards for d in c["detections"]})
        blades = sorted({c["blade"] for c in cards})
        data_blob = json.dumps({"turbine": turbine.turbine_id,
                                "health_index": turbine.overall_health_index,
                                "defect_distribution": turbine.defect_distribution(),
                                "classes": classes, "blades": blades,
                                "cards": cards, "generated": now},
                             ensure_ascii=False)

        html = _DASHBOARD_TEMPLATE.replace("__DATA__", data_blob)
        dashboard_file.write_text(html, encoding="utf-8")
        return dashboard_file


